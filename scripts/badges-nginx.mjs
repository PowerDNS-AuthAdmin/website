#!/usr/bin/env node
// Writes deploy/nginx-badges.conf from src/badges.mjs: one exact-match nginx location
// per footer badge, each fetching one fixed upstream URL server-side and caching it.
//
//   node scripts/badges-nginx.mjs          # regenerate deploy/nginx-badges.conf
//   node scripts/badges-nginx.mjs --check  # exit 1 if the committed file is stale
//
// The host includes the file inside the HTTPS server block, and needs the cache zone
// once at http level (deploy/nginx.conf.example shows both). Why a proxy at all: the
// site's only third party is Google Analytics, so badges must not make every visitor's
// browser call GitHub, shields.io, scorecard.dev and the rest.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { badgePath, badges } from "../src/badges.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "deploy", "nginx-badges.conf");

// nginx needs the URL inside double quotes; none of these contain one, but refuse
// rather than emit a config an upstream URL could break out of.
for (const b of badges) {
  if (!/^https:\/\/[^\s"';{}\\$]+$/.test(b.src)) throw new Error(`badge ${b.id}: unsafe upstream URL ${b.src}`);
  if (!/^[a-z0-9-]+$/.test(b.id)) throw new Error(`badge ${b.id}: id must be [a-z0-9-]`);
}

const location = (b) => `location = ${badgePath(b.id)} {
    set $badge_upstream "${b.src}";
    include snippets/pda-badge-proxy.conf;
}`;

const body = `# GENERATED by scripts/badges-nginx.mjs from src/badges.mjs - do not edit by hand.
# Footer badges, proxied so visitors never contact the badge services themselves.
# Install as /etc/nginx/snippets/pda-badges.conf, with deploy/nginx-badge-proxy.conf as
# /etc/nginx/snippets/pda-badge-proxy.conf, and include it inside the HTTPS server block:
#   include snippets/pda-badges.conf;
# Needs once at http level (e.g. conf.d/pda-badges-cache.conf):
#   proxy_cache_path /var/cache/nginx/pda-badges levels=1:2 keys_zone=pda_badges:1m max_size=20m inactive=7d use_temp_path=off;

${badges.map(location).join("\n\n")}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(out, "utf8"); } catch {}
  if (current !== body) {
    console.error("✗ deploy/nginx-badges.conf is stale: run node scripts/badges-nginx.mjs");
    process.exit(1);
  }
  console.log(`✓ deploy/nginx-badges.conf matches src/badges.mjs (${badges.length} badges)`);
} else {
  writeFileSync(out, body);
  console.log(`wrote deploy/nginx-badges.conf (${badges.length} badges)`);
}
